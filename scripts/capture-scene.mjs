import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
await mkdir('.impeccable/review/scene', { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
await page.goto('http://127.0.0.1:4173/materials-lab/');
await page.getByTestId('prediction-ready').waitFor();
await page.locator('canvas').waitFor();
await page.evaluate(() => document.fonts.ready);
await page.screenshot({ path: '.impeccable/review/scene/desktop.png', fullPage: true });
await page.getByRole('button', { name: '3 Hold', exact: true }).click();
await page.locator('.specimen-panel').screenshot({ path: '.impeccable/review/scene/hold.png' });
await page.getByRole('button', { name: 'Specimen close-up', exact: true }).click();
await page.locator('.specimen-panel').screenshot({ path: '.impeccable/review/scene/detail.png' });
await page.setViewportSize({ width: 390, height: 844 });
await page.getByRole('button', { name: 'Apparatus', exact: true }).click();
await page.screenshot({ path: '.impeccable/review/scene/mobile.png', fullPage: true });
console.log(JSON.stringify({ errors, mobileWidth: await page.evaluate(() => document.documentElement.scrollWidth) }));
await browser.close();
